#!/usr/bin/env python3
"""Deterministic stratified task subset for a SOPBench pilot.

    ~/Code/SOPBench/.venv/bin/python scripts/eval/sopbench_sample.py \\
        --domain hotel --n 40 --seed 20260924 \\
        --out evals/sopbench-bank-asop/hotel-pilot-40.json

Strata are `(user_goal, action_should_succeed)`, so a pilot sees every action
type in both directions — the split T2 exists to report. Allocation:

  1. every stratum gets min(2, size);
  2. the remaining slots go proportionally to stratum size, by largest
     remainder (ties broken by stratum key, so the result never depends on dict
     order), never exceeding a stratum's size — excess is re-allocated;
  3. positions inside each stratum are drawn with `random.Random(seed)`, one
     generator walked in sorted-stratum order.

The output is a sorted JSON list of POSITIONAL task indices — the index
`run_simulation.py` uses, i.e. goals in file order, tasks in list order — which
is what `--task-ids`, `sopbench_shard.py merge --subset` and the scorer's
`ASOP_SUBSET` all read. A sibling `.md` records the stratum table.
"""

from __future__ import annotations

import argparse
import json
import math
import random
from pathlib import Path


def strata_of(tasks_by_goal: dict) -> dict:
    """(goal, should_succeed) -> sorted positional indices, in run_simulation order."""
    out: dict = {}
    pos = 0
    for goal, arr in tasks_by_goal.items():
        for t in arr:
            out.setdefault((goal, bool(t["action_should_succeed"])), []).append(pos)
            pos += 1
    return out


def allocate(sizes: dict, n: int, floor: int = 2) -> dict:
    """Per-stratum sample counts summing to n (or to the population if smaller)."""
    total = sum(sizes.values())
    n = min(n, total)
    alloc = {k: min(floor, s) for k, s in sizes.items()}
    if sum(alloc.values()) > n:
        raise SystemExit(f"n={n} cannot give every one of {len(sizes)} strata its floor")
    while sum(alloc.values()) < n:
        open_ = {k: s for k, s in sizes.items() if alloc[k] < s}
        room = n - sum(alloc.values())
        weight = sum(open_.values())
        quota = {k: room * s / weight for k, s in open_.items()}
        added = 0
        for k in open_:
            take = min(math.floor(quota[k]), sizes[k] - alloc[k])
            alloc[k] += take
            added += take
        left = n - sum(alloc.values())
        # largest remainder among strata that still have room; key breaks ties
        for k in sorted(open_, key=lambda k: (-(quota[k] - math.floor(quota[k])), k)):
            if left == 0:
                break
            if alloc[k] < sizes[k]:
                alloc[k] += 1
                left -= 1
                added += 1
        if added == 0:
            break
    return alloc


def sample(tasks_by_goal: dict, n: int, seed: int) -> tuple[list, list]:
    strata = strata_of(tasks_by_goal)
    alloc = allocate({k: len(v) for k, v in strata.items()}, n)
    rng = random.Random(seed)
    picked: list = []
    table = []
    for k in sorted(strata):
        chosen = sorted(rng.sample(strata[k], alloc[k]))
        picked.extend(chosen)
        table.append((k, len(strata[k]), alloc[k], chosen))
    return sorted(picked), table


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--sopbench", type=Path, default=Path.home() / "Code" / "SOPBench")
    ap.add_argument("--domain", required=True)
    ap.add_argument("--n", type=int, required=True)
    ap.add_argument("--seed", type=int, required=True)
    ap.add_argument("--out", type=Path, required=True)
    args = ap.parse_args()

    tasks = json.loads((args.sopbench / "data" / f"{args.domain}_tasks.json").read_text())
    ids, table = sample(tasks, args.n, args.seed)
    args.out.write_text(json.dumps(ids) + "\n")
    total = sum(len(v) for v in tasks.values())
    lines = [
        f"# `{args.out.name}` — {len(ids)} of {total} `{args.domain}` tasks",
        "",
        f"Generated by `scripts/eval/sopbench_sample.py --domain {args.domain} "
        f"--n {args.n} --seed {args.seed}`. Deterministic: re-running reproduces "
        "the list byte for byte. Strata = `(user_goal, action_should_succeed)`; "
        "floor min(2, size), remainder proportional to size by largest remainder.",
        "",
        f"{len(table)} strata. Positions are `run_simulation.py`'s task indices.",
        "",
        "| user_goal | should succeed | stratum size | sampled | positions |",
        "|---|---|---|---|---|",
    ]
    for (goal, ok), size, k, chosen in table:
        lines.append(f"| `{goal}` | {'yes' if ok else 'no'} | {size} | {k} | "
                     f"{', '.join(map(str, chosen))} |")
    lines.append(f"| **total** | | **{total}** | **{len(ids)}** | |")
    args.out.with_suffix(".md").write_text("\n".join(lines) + "\n")
    print(f"{len(ids)} tasks across {len(table)} strata -> {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
